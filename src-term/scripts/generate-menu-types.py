"""Generate the terminal's menu data contracts from the daemon's Rust structs.
Run from any directory: python3 src-term/scripts/generate-menu-types.py
Enum tokens come from snapshot/projection/tokens.rs; opaque extension documents
remain JSON until interpreted by the screen protocol renderer.
"""
from pathlib import Path
import re
root = Path(__file__).resolve().parents[2]
sources = list((root/'src-agent/src/ipc/proto/snapshot').glob('*.rs'))
sources += list((root/'src-agent/src/model').rglob('*.rs'))
sources += [root/'src-agent/src/app/sec/mod.rs', root/'src-agent/src/ipc/proto/mod.rs', root/'src-agent/src/app/mode/notifications.rs']
structs = {}
for path in sources:
    text = path.read_text()
    for name, body in re.findall(r'pub struct (\w+)\s*\{(.*?)^\}', text, re.M|re.S):
        fields = re.findall(r'^\s*pub (\w+):\s*([^\n]+),\s*$', body, re.M)
        if name=="NotificationsState":fields=[(field,typ) for field,typ in fields if field not in ("pending","refreshed")]
        if fields and name not in structs: structs[name] = fields

def split(text):
    parts=[]; start=0; depth=0
    for i,c in enumerate(text):
        if c in '<([': depth+=1
        if c in '>)]': depth-=1
        if c==',' and depth==0: parts.append(text[start:i].strip());start=i+1
    parts.append(text[start:].strip())
    return [p for p in parts if p]
# Named event variants are parsed from the authoritative protocol too.
proto = (root/'src-agent/src/ipc/proto/mod.rs').read_text()
event_body = proto.split('pub enum DaemonEvent {', 1)[1].split('\n}', 1)[0]
event_names = ['MenuResult','MenuCapabilities','Notifications','WebSearchValues','SettingsValues','ModelList','ModelRoutes','AgentsValues','AgentOp','OAuthState','StoreCatalogue','StoreItemDetail','InstalledExtensions','ExtensionOpResult','McpStatus','EffortOptions','PasteBody','AttachmentLocated']
events = {}
for name in event_names:
    match = re.search(r'\b'+name+r'\s*\{([^}]+)\}', event_body, re.S)
    assert match, name
    body = re.sub(r'//[^\n]*|#\[[^\n]*\]', '', match.group(1))
    fields = [tuple(part.strip().split(':', 1)) for part in split(body) if ':' in part]
    structs[name+'Event'] = fields
    events[name] = name+'Event'
seen=set(); queue=[]
def convert(typ):
    typ=typ.strip()
    if typ.startswith('('): return '['+', '.join(convert(t) for t in split(typ[1:-1]))+']'
    if '<' in typ:
        outer,inner=typ.split('<',1);outer=outer.split('::')[-1];inner=inner[:-1];args=split(inner)
        if outer in ('Box','Arc'): return convert(args[0])
        if outer=='Option': return convert(args[0])+' | null'
        if outer in ('Vec','HashSet'): return f'Array<{convert(args[0])}>'
        if outer in ('HashMap','BTreeMap'): return f'Record<{convert(args[0])}, {convert(args[1])}>'
        return 'JsonValue'
    typ=typ.split('::')[-1]
    if typ in ('String','PathBuf','ApiType','ModelRole','OAuthProvider','InternetMode','MouseCapture','ThemeMode'): return 'string'
    if re.fullmatch(r'[uif]\d+|usize|isize',typ): return 'number'
    if typ=='bool': return 'boolean'
    if typ in ('Value','SearchKey'): return 'JsonValue' if typ=='Value' else 'string'
    if typ in structs:
        if typ not in seen: seen.add(typ);queue.append(typ)
        return typ
    return 'string' # pure snapshot enum wire tokens

roots=['SettingsSnapshot','AgentsSnapshot','McpSnapshot','ExtensionsSnapshot','ExtStoreSnapshot','ExtScreenSnapshot','SecuritySnapshot','HelpSnapshot','UsageSnapshot','EffortSnapshot','RemoteSnapshot','SessionHubSnapshot','PickerSnapshot','OnboardSnapshot','OnboardProviderSnapshot','KeyInputSnapshot','AttachmentsSnapshot','NotificationsState']
for name in roots + list(events.values()): convert(name)
output=['// Generated by scripts/generate-menu-types.py. Do not edit by hand.', 'export type JsonValue = null | string | number | boolean | JsonValue[] | { [key: string]: JsonValue }','']
while queue:
    name=queue.pop(0)
    output.append(f'export interface {name} {{')
    for field,typ in structs[name]: output.append(f'  {field}: {convert(typ)}')
    output += ['}', '']
output += ['export interface MenuData {'] + [f'  {name.removesuffix("Snapshot").removesuffix("State")}: {name}' for name in roots] + ['}', '']
oauth_source=(root/'src-agent/src/app/mode/settings/oauth_types.rs').read_text().split('pub const OAUTH_OPTIONS:',1)[1]
import json
output += ['export const OAUTH_OPTIONS = '+json.dumps(re.findall(r'"([^"]+)"', oauth_source))+' as const', '']
output += ['export interface DaemonMenuEvents {'] + [f'  {name}: {typ}' for name,typ in events.items()] + ['}', '']
(root/'src-term/src/modes/data.ts').write_text('\n'.join(output))
